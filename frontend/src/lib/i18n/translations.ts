type DeepStringify<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepStringify<T[K]>;
};

export type TranslationKeys = DeepStringify<typeof t.fr>;

export function getTranslations(locale: Locale): TranslationKeys {
  if (locale === "fr") return t.fr as TranslationKeys;
  return t.ar as TranslationKeys;
}

/** Migre d’anciennes préférences EN → FR. */
export function normalizeAppLocale(value: unknown): Locale {
  if (value === "ar") return "ar";
  return "fr";
}
