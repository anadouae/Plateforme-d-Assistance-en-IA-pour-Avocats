def build_plaidoirie_system(type_id: str | None) -> str:
    tid = (type_id or "libre").strip()
    if tid not in PLAIDOIRIE_TYPES:
        tid = "libre"
    return PLAIDOIRIE_AGENT_SYSTEM.format(
        type_id=tid,
        type_label=PLAIDOIRIE_TYPES[tid],
    )


